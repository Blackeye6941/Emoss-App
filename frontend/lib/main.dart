class EmotionDetector {
  static const Map<String, List<String>> _keywords = {
    'joy': ['happy', 'excited', 'great', 'amazing', 'wonderful', 'thrilled',
            'proud', 'love', 'fantastic', 'excellent', 'promoted', 'celebrate'],
    'sadness': ['sad', 'depress', 'cry', 'lonely', 'hopeless', 'grief',
                'loss', 'empty', 'numb', 'worthless', 'miss', 'alone', 'hurt'],
    'anger': ['angry', 'anger', 'furious', 'rage', 'frustrated', 'irritated',
              'annoyed', 'mad', 'upset', 'blame', 'unfair', 'hate'],
    'fear': ['scared', 'afraid', 'anxious', 'anxiety', 'fear', 'terror',
             'panic', 'worry', 'overwhelm', 'stress', 'nervous', 'terrified'],
    'disgust': ['disgust', 'sick', 'gross', 'repuls', 'awful', 'horrible'],
    'surprise': ['surprise', 'shock', 'unexpected', 'sudden', 'unbelievable',
                 'wow', 'omg', 'cant believe'],
  };

  static MapEntry<String, double> detect(String text) {
    final lower = text.toLowerCase();
    final scores = <String, int>{};

    for (final entry in _keywords.entries) {
      int count = 0;
      for (final kw in entry.value) {
        if (lower.contains(kw)) count++;
      }
      if (count > 0) scores[entry.key] = count;
    }

    if (scores.isEmpty) return const MapEntry('neutral', 0.5);

    final best = scores.entries.reduce((a, b) => a.value > b.value ? a : b);
    final confidence = (0.6 + (best.value * 0.1)).clamp(0.6, 0.95);
    return MapEntry(best.key, confidence);
  }

  static Color getEmotionColor(String emotion) {
    return switch (emotion) {
      'joy'      => const Color(0xFFFFD700),
      'sadness'  => const Color(0xFF6495ED),
      'anger'    => const Color(0xFFFF4444),
      'fear'     => const Color(0xFFAA44FF),
      'disgust'  => const Color(0xFF44AA44),
      'surprise' => const Color(0xFFFF8C00),
      _          => const Color(0xFF888888),
    };
  }

  static String getEmotionEmoji(String emotion) {
    return switch (emotion) {
      'joy'      => '😊',
      'sadness'  => '💙',
      'anger'    => '😤',
      'fear'     => '😰',
      'disgust'  => '😣',
      'surprise' => '😮',
      _          => '😐',
    };
  }
}

