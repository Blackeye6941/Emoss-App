class HiveService {
  static const String _conversationsBox = 'conversations';
  static const String _messagesBox = 'messages';
  static final _uuid = const Uuid();

  static Box<ConversationModel> get _conversations =>
      Hive.box<ConversationModel>(_conversationsBox);

  static Box<MessageModel> get _messages =>
      Hive.box<MessageModel>(_messagesBox);

  // ── Conversations ──────────────────────────────────────────

  static Future<ConversationModel> createConversation(String firstMessage) async {
    final id = _uuid.v4();
    final now = DateTime.now();
    final conv = ConversationModel(
      id: id,
      title: firstMessage.length > 40
          ? '${firstMessage.substring(0, 40)}...'
          : firstMessage,
      createdAt: now,
      updatedAt: now,
      lastMessage: firstMessage,
      dominantEmotion: 'neutral',
    );
    await _conversations.put(id, conv);
    return conv;
  }

  static List<ConversationModel> getAllConversations() {
    final list = _conversations.values.toList();
    list.sort((a, b) => b.updatedAt.compareTo(a.updatedAt));
    return list;
  }

  static Future<void> updateConversation(
      String id, String lastMessage, String emotion) async {
    final conv = _conversations.get(id);
    if (conv != null) {
      conv.lastMessage = lastMessage;
      conv.updatedAt = DateTime.now();
      conv.dominantEmotion = emotion;
      await conv.save();
    }
  }

  static Future<void> deleteConversation(String id) async {
    // Delete all messages in this conversation
    final toDelete = _messages.values
        .where((m) => m.conversationId == id)
        .map((m) => m.id)
        .toList();
    for (final msgId in toDelete) {
      await _messages.delete(msgId);
    }
    await _conversations.delete(id);
  }

  // ── Messages ───────────────────────────────────────────────

  static Future<MessageModel> saveMessage({
    required String conversationId,
    required String content,
    required bool isUser,
    required String emotion,
    required double emotionConfidence,
  }) async {
    final id = _uuid.v4();
    final msg = MessageModel(
      id: id,
      conversationId: conversationId,
      content: content,
      isUser: isUser,
      timestamp: DateTime.now(),
      emotion: emotion,
      emotionConfidence: emotionConfidence,
    );
    await _messages.put(id, msg);
    return msg;
  }

  static List<MessageModel> getMessagesForConversation(String conversationId) {
    final list = _messages.values
        .where((m) => m.conversationId == conversationId)
        .toList();
    list.sort((a, b) => a.timestamp.compareTo(b.timestamp));
    return list;
  }

  static int getTotalMessageCount() => _messages.length;
  static int getTotalConversationCount() => _conversations.length;
}

