  String _currentEmotion = 'neutral';
  double _currentConfidence = 0.5;

  late AnimationController _typingController;
  late Animation<double> _typingAnimation;

  @override
  void initState() {
    super.initState();
    _typingController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 1000),
    )..repeat(reverse: true);
    _typingAnimation = Tween<double>(begin: 0.4, end: 1.0)
        .animate(_typingController);
    _loadMessages();
  }

  @override
  void dispose() {
    _controller.dispose();
    _scrollController.dispose();
    _focusNode.dispose();
    _typingController.dispose();
    super.dispose();
  }

  void _loadMessages() {
    setState(() {
      _messages =
          HiveService.getMessagesForConversation(widget.conversation.id);
    });
    _scrollToBottom();
  }

  void _scrollToBottom() {
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_scrollController.hasClients) {
        _scrollController.animateTo(
          _scrollController.position.maxScrollExtent,
          duration: const Duration(milliseconds: 300),
          curve: Curves.easeOut,
        );
      }
    });
  }

  Future<void> _sendMessage() async {
    final text = _controller.text.trim();
    if (text.isEmpty || _isTyping) return;

    _controller.clear();

    // Detect emotion
    final emotionResult = EmotionDetector.detect(text);
    _currentEmotion = emotionResult.key;
    _currentConfidence = emotionResult.value;

    // Save user message
    final userMsg = await HiveService.saveMessage(
      conversationId: widget.conversation.id,
      content: text,
      isUser: true,
      emotion: _currentEmotion,
      emotionConfidence: _currentConfidence,
    );

    setState(() {
      _messages.add(userMsg);
      _isTyping = true;
    });
    _scrollToBottom();

    // Update conversation
    await HiveService.updateConversation(
        widget.conversation.id, text, _currentEmotion);

    // Get AI response
    final response =
        await MockAIService.getResponse(text, _currentEmotion);

    // Save AI message
    final aiMsg = await HiveService.saveMessage(
      conversationId: widget.conversation.id,
      content: response,
      isUser: false,
      emotion: _currentEmotion,
      emotionConfidence: _currentConfidence,
    );

    await HiveService.updateConversation(
        widget.conversation.id, response, _currentEmotion);

    setState(() {
      _messages.add(aiMsg);
      _isTyping = false;
    });
    _scrollToBottom();
  }

